    <p>Java es un lenguaje de programación orientado a objetos que se utiliza para desarrollar diferentes tipos de aplicaciones. Se caracteriza por tener una sintaxis organizada, ser multiplataforma y permitir la reutilización de código.</p>
    <h1>Sintaxis de Java</h1>
    <p>La sintaxis de Java es el conjunto de reglas que debemos seguir para escribir correctamente un programa. Todo programa generalmente contiene una clase y un método principal llamado main, donde comienza la ejecución.</p>
    <h1>Estructuras repetitivas</h1>
    <p>Las estructuras repetitivas, también conocidas como ciclos o bucles, permiten ejecutar varias veces un bloque de código sin tener que escribirlo repetidamente.</p>

    <p>En Java existen tres estructuras principales:</p>
    <p>For: se utiliza cuando conocemos la cantidad de veces que queremos repetir una instrucción.</p>

<p>While: repite un bloque de código mientras una condición sea verdadera.</p>

<p>Do While: ejecuta el código al menos una vez y después verifica la condición.</p>
<h1>Programación Orientada a Objetos (Atributos y Métodos)</h1>
<p>La Programación Orientada a Objetos (POO) es una forma de programar que organiza el código mediante clases y objetos.</p>
<h1>Herencia:</h1>
<p> Permite que una clase hija (subclase) adquiera los atributos y métodos de una clase padre (superclase) para reutilizar código. Se implementa usando la palabra reservada extends (ej. public class Perro extends Animal).</p>
    
